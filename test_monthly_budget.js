const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={window:{InvestmentLogic:{validateEntry:e=>{if(!Number.isFinite(e.amount)||e.amount<0)throw Error('invalid');}}},document:{getElementById:()=>null}};
vm.runInNewContext(fs.readFileSync('archive/legacy_ui/monthly_budget.js','utf8'),context);
const calc=context.window.MonthlyBudgetLogic.calculate,date='2026-10-14';
const summary=(code,status='buy',us=false)=>({symbol:code,name:code,status,date,metrics:{price:2},details:{strategy_mode:us?'us_monthly_trend':'broad_individual'}});
const entry=(code,amount,action='买入',d=date)=>({code,amount,action,date:d});
assert.equal(calc(2000,['1'],[summary('1')],[],date).suggested,1000);
assert.equal(calc(2000,['1'],[summary('1')],[entry('1',1000)],date).suggested,0);
assert.equal(calc(2000,['1'],[summary('1','add')],[entry('1',1000)],date).suggested,1000);
assert.equal(calc(2000,['1'],[summary('1','add')],[entry('1',2000),entry('1',2000,'卖出')],date).suggested,0);
assert.equal(calc(2000,['1'],[summary('1','watch')],[],date).suggested,0);
assert.equal(calc(2000,['1'],[summary('1','add')],[entry('2',1800)],date).suggested,200);
assert.equal(calc(2000,['1','2'],[summary('1'),summary('2','watch')],[],date).suggested,500);
assert.equal(calc(2000,['1'],[summary('1','buy',true)],[],date).suggested,0);
assert.equal(calc(2000,['1'],[summary('1','buy',true)],[],date,{'1':17}).suggested,0);
assert.equal(calc(2000,['1'],[summary('1','buy',true)],[],date,{'1':1}).suggested,1000);
assert.equal(calc(2000,['1'],[summary('1')],[entry('1',2000,'买入','2026-09-14')],date).suggested,1000);
